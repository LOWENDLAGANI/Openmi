import type { CommitMode } from '../../shared/types';
import { assertNoDestructiveChange } from '../agent/patch';
import { AppError } from '../lib/errors';
import { log } from '../lib/logger';
import type { CommitResult, PatchFile } from '../workflows/types';
import { createOctokit, mapGithubError, parseRepoFullName } from './client';
import { createBlob, getCommitTreeSha, getRepoTree, type TreeEntry } from './repo';

export interface CommitPatchInput {
  token: string;
  repoFullName: string;
  baseSha: string;
  branch: string;
  files: PatchFile[];
  mode: CommitMode;
  taskId: string;
  summary: string;
  prompt: string;
}

/**
 * Verifies each patch target against the *current* base tree.
 * - update targets must still exist (nothing was deleted under us)
 * - update targets must be unchanged since the snapshot (no clobbering a
 *   concurrent human edit); a mismatch aborts instead of overwriting
 * - create targets may already exist only if they appeared after the snapshot,
 *   which we treat as an overwrite-with-warning and surface to the user
 */
export function assertPatchTargets(
  files: PatchFile[],
  tree: TreeEntry[],
): { overwrites: string[] } {
  const byPath = new Map(tree.map((entry) => [entry.path, entry]));
  const overwrites: string[] = [];

  for (const file of files) {
    const current = byPath.get(file.path);

    if (file.operation === 'update') {
      if (!current) {
        throw new AppError(
          'GITHUB_CONFLICT',
          `"${file.path}" no longer exists on the base branch; the task was abandoned to avoid overwriting changes`,
        );
      }
      if (file.baseBlobSha && current.sha !== file.baseBlobSha) {
        throw new AppError(
          'GITHUB_CONFLICT',
          `"${file.path}" changed on GitHub while the agent was working. Re-run the task to apply it on top of the new content.`,
        );
      }
      continue;
    }

    if (current) overwrites.push(file.path);
  }

  return { overwrites };
}

function buildCommitMessage(input: { summary: string; prompt: string; taskId: string }): string {
  const subject = input.summary.split('\n')[0]?.slice(0, 60) ?? 'apply changes';
  return [
    `openmi: ${subject}`,
    '',
    input.prompt.slice(0, 400),
    '',
    `Generated by OpenMi · task ${input.taskId}`,
  ].join('\n');
}

/**
 * Applies a validated patch set as ONE atomic commit on top of `baseSha`.
 *
 * Safety properties:
 * 1. Every blob is new; no existing file content is mutated in place.
 * 2. The new tree is created with `base_tree`, so untouched files are retained
 *    by GitHub itself.
 * 3. The resulting tree is fetched and checked to be a superset of the base
 *    tree before a commit object exists.
 * 4. The branch ref is only ever fast-forwarded (`force: false`).
 */
export async function commitPatchSet(input: CommitPatchInput): Promise<CommitResult> {
  const { owner, repo } = parseRepoFullName(input.repoFullName);
  const octokit = createOctokit(input.token);

  try {
    const baseTreeSha = await getCommitTreeSha(octokit, input.repoFullName, input.baseSha);
    const baseTree = await getRepoTree(octokit, input.repoFullName, baseTreeSha);
    const { overwrites } = assertPatchTargets(input.files, baseTree.entries);
    if (overwrites.length > 0) {
      log.warn('github.overwrite_create', { files: overwrites, taskId: input.taskId });
    }

    const blobShas = await Promise.all(
      input.files.map((file) => createBlob(octokit, input.repoFullName, file.content)),
    );

    const treeEntries = input.files.map((file, index) => ({
      path: file.path,
      mode: '100644' as const,
      type: 'blob' as const,
      sha: blobShas[index] as string,
    }));

    const createdTree = await octokit.rest.git.createTree({
      owner,
      repo,
      base_tree: baseTreeSha,
      tree: treeEntries,
    });

    // Invariant check BEFORE the commit object exists.
    const newTree = await getRepoTree(octokit, input.repoFullName, createdTree.data.sha);
    const patchedPaths = new Set(input.files.map((file) => file.path));

    if (!baseTree.truncated) {
      assertNoDestructiveChange(
        baseTree.entries.map((entry) => entry.path),
        newTree.entries.map((entry) => entry.path),
      );
    } else {
      log.warn('github.base_tree_truncated', {
        taskId: input.taskId,
        baseFiles: baseTree.entries.length,
      });
      assertNoDestructiveChange(
        baseTree.entries
          .map((entry) => entry.path)
          .filter((path) => !patchedPaths.has(path)),
        newTree.entries.map((entry) => entry.path),
      );
    }

    const missing = input.files
      .filter((file) => !newTree.entries.some((entry) => entry.path === file.path))
      .map((file) => file.path);
    if (missing.length > 0) {
      throw new AppError('PATCH_REJECTED', `Commit blocked: patched files missing (${missing[0]})`);
    }

    const message = buildCommitMessage({
      summary: input.summary,
      prompt: input.prompt,
      taskId: input.taskId,
    });

    const commit = await octokit.rest.git.createCommit({
      owner,
      repo,
      message,
      tree: createdTree.data.sha,
      parents: [input.baseSha],
    });

    const commitUrl = `https://github.com/${owner}/${repo}/commit/${commit.data.sha}`;

    if (input.mode === 'pull_request') {
      const prBranch = `openmi/task-${input.taskId.slice(0, 8)}`;
      await octokit.rest.git.createRef({
        owner,
        repo,
        ref: `refs/heads/${prBranch}`,
        sha: commit.data.sha,
      });

      const pr = await octokit.rest.pulls.create({
        owner,
        repo,
        title: `OpenMi: ${input.summary.split('\n')[0]?.slice(0, 80) ?? 'changes'}`,
        head: prBranch,
        base: input.branch,
        body: [
          input.summary,
          '',
          `> ${input.prompt.slice(0, 500)}`,
          '',
          `Generated by OpenMi · task ${input.taskId}`,
        ].join('\n'),
      });

      return {
        commitSha: commit.data.sha,
        commitUrl,
        branch: prBranch,
        filesChanged: input.files.length,
        mode: 'pull_request',
        pullRequestUrl: pr.data.html_url,
      };
    }

    // Fast-forward only. `force: false` makes GitHub reject any non-fast-forward
    // update, which is our last line of defence against history rewriting.
    await octokit.rest.git.updateRef({
      owner,
      repo,
      ref: `heads/${input.branch}`,
      sha: commit.data.sha,
      force: false,
    });

    return {
      commitSha: commit.data.sha,
      commitUrl,
      branch: input.branch,
      filesChanged: input.files.length,
      mode: 'direct',
    };
  } catch (error) {
    throw mapGithubError(error, 'commitPatchSet');
  }
}

/** Exposed for tests: octokit-free description of the commit we intend to make. */
export function describeCommitPlan(input: {
  files: PatchFile[];
  branch: string;
  mode: CommitMode;
}): { paths: string[]; branch: string; mode: CommitMode; atomic: true } {
  return {
    paths: input.files.map((file) => file.path),
    branch: input.branch,
    mode: input.mode,
    atomic: true,
  };
}

