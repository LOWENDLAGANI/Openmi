-- ── Openmi — the Supabase schema ────────────────────────────────────────────
--
-- This file is the replacement for `database.rules.json`. Every node of the old
-- Realtime Database tree is a table here, and every `.read`/`.write` rule that
-- tree carried is a row-level security policy below. The two properties the old
-- build was written around survive unchanged:
--
--   1. There is no service-role key anywhere in the app. Every request is made
--      with the caller's own JWT, so RLS — not the deployment — decides access.
--   2. Elevation is decided by one administrator address, and only in the
--      database. The app may *check* the same address to give a clearer error,
--      but it cannot grant what a policy refuses.
--
-- Run it with `supabase db push`, or paste it into the SQL editor of a fresh
-- project. It is idempotent enough to re-run: tables are created only when they
-- are absent and every policy is dropped before it is recreated.

-- No extension is required. Every id in this schema is either supplied by the
-- client, defaulted from `auth.uid()`, or generated by Supabase's own auth
-- tables — so `gen_random_uuid()` and the rest of pgcrypto never appear, and the
-- file applies cleanly to any Postgres that has an `auth` schema.

-- ── Who the administrator is ────────────────────────────────────────────────
-- One row, one address. RLS cannot read an environment variable, so the address
-- the policies compare against has to live in the database. The app also has
-- OPENMI_ADMIN_EMAIL, and the two must name the same person: the environment
-- copy is what lets a route answer with a readable message, and this row is what
-- actually decides. `supabase/seed.sql` seeds it; change both together.
create table if not exists public.app_admin (
  id integer primary key default 1 check (id = 1),
  email text not null
);

alter table public.app_admin enable row level security;
-- Deliberately no policies: nobody reads this table directly. `is_admin()` below
-- is the only door, so the address is never handed to a browser as data.

/**
 * True when the caller's verified JWT carries the administrator's address.
 *
 * `auth.jwt()` is the decoded, signature-verified token — the same thing
 * `auth.token.email` meant to the Realtime Database rules. SECURITY DEFINER is
 * what lets it read `app_admin` without granting anyone a SELECT on it; the
 * pinned `search_path` is what stops a shadowed table from answering instead.
 */
create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select exists (
    select 1
    from public.app_admin
    where lower(email) = lower(coalesce(auth.jwt() ->> 'email', ''))
  );
$$;

revoke all on function public.is_admin() from public;
grant execute on function public.is_admin() to anon, authenticated;

-- ── Runtime configuration ───────────────────────────────────────────────────
-- Replaces `config/`. One row. Publicly readable (the server reads it with no
-- credential, exactly as the old open `.read` allowed) and writable only by the
-- administrator.
create table if not exists public.app_config (
  id smallint primary key default 1 check (id = 1),
  chat_enabled boolean not null default true,
  search_enabled boolean not null default true,
  announcement text not null default '',
  daily_chat_cap integer not null default 0 check (daily_chat_cap >= 0),
  bans jsonb not null default '[]'::jsonb,
  maintenance_enabled boolean not null default false,
  maintenance_message text not null default 'Openmi is down for maintenance. Please check back soon.',
  updated_at timestamptz not null default now()
);

alter table public.app_config enable row level security;

-- `config` was readable with no token at all, and the server still reads it that
-- way on every request: it enforces the controls, so it cannot depend on an
-- identity to find out whether it should. Reading the config grants nothing —
-- enforcement is server-side, and a client that lies about it only hides
-- controls from itself.
drop policy if exists app_config_public_read on public.app_config;
create policy app_config_public_read on public.app_config
  for select to anon, authenticated
  using (true);

drop policy if exists app_config_admin_write on public.app_config;
create policy app_config_admin_write on public.app_config
  for all to authenticated
  using (public.is_admin())
  with check (public.is_admin());

grant select on public.app_config to anon, authenticated;
grant insert, update, delete on public.app_config to authenticated;

-- The one live subscription in the app: an administrator's change to the config
-- reaches open tabs without a reload. Wrapped because `supabase_realtime` only
-- exists in a hosted Supabase project, and a plain Postgres run of this file
-- must still succeed.
do $$
begin
  alter publication supabase_realtime add table public.app_config;
exception
  when undefined_object then null;
  when duplicate_object then null;
end
$$;
